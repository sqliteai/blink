#!/usr/bin/env python3
"""Generate the measured sections of docs/RESULTS.md from the result files.

Sections 1 (size), 2 (latency) and 3 (accuracy) were hand-copied from terminal
output for several revisions, and every one of them went stale the moment the
architecture changed: section 3 quoted models that no longer loaded, and
sections 1 and 2 quoted a parameter count from before the cross layer existed.
This reads `results/bench-*.jsonl` and `results/eval-*.json` and emits the
markdown, so the document cannot claim something the results do not.

The prose around each block is hand-written and is left alone; only what sits
between the markers is replaced.

    python scripts/report_results.py            # print
    python scripts/report_results.py --write    # splice into docs/RESULTS.md
"""

from __future__ import annotations

import argparse
import json
import statistics
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))

SEEDS = (7, 17, 27)
MARK = "generated by scripts/report_results.py"


def begin(name: str) -> str:
    return f"<!-- BEGIN {name} ({MARK}) -->"


def end(name: str) -> str:
    return f"<!-- END {name} -->"

WORKLOADS = {
    "tiny-synthetic": ("blink-tiny", "data/synthetic/test.jsonl"),
    "small-synthetic": ("blink-small", "data/synthetic/test.jsonl"),
    "tiny-wanli": ("blink-tiny (WANLI)", "data/wanli/test.jsonl"),
}
FIXTURES = {
    "authored144": "data/fixtures/authored144.jsonl",
    "perturbations108": "data/fixtures/perturbations108.jsonl",
}


# ------------------------------------------------------------------ loading


def evaluate(label: str, data: str, extra: list[str] | None = None,
             model_label: str | None = None) -> dict | None:
    """Run one evaluation if its report is missing, and return the report.

    `model_label` differs from `label` when one model is scored on several
    corpora: the report is named for the pair, the container for the model.
    """
    report = ROOT / f"results/eval-{label}.json"
    model = ROOT / f"artifacts/blink-{model_label or label}.blink"
    # A committed report stands on its own: blink-small's containers are not
    # in the repository, and its numbers must not vanish because of that.
    if report.exists():
        return json.loads(report.read_text())
    if not model.exists():
        return None
    if not report.exists():
        subprocess.run(
            [sys.executable, str(ROOT / "eval/evaluate.py"), str(model),
             str(ROOT / data), "--json", str(report),
             "--predictions", str(ROOT / f"results/predictions/{label}.jsonl"),
             "--quiet", *(extra or [])],
            check=True, cwd=ROOT,
        )
    return json.loads(report.read_text())


def across_seeds(prefix: str, data: str, extra=None) -> list[dict]:
    out = []
    for seed in SEEDS:
        report = evaluate(f"{prefix}-s{seed}", data, extra)
        if report:
            out.append(report)
    return out


def stat(values: list[float], places: int = 4) -> str:
    if not values:
        return "—"
    if len(values) == 1:
        return f"{values[0]:.{places}f}"
    return f"{statistics.mean(values):.{places}f} ± {statistics.stdev(values):.{places}f}"


def pick(reports: list[dict], key: str) -> list[float]:
    return [r["metrics"][key] for r in reports]


def pick_family(reports: list[dict], family: str, key: str = "top1") -> list[float]:
    return [r["by_family"][family][key] for r in reports
            if family in r.get("by_family", {})]


# ------------------------------------------------- sections 1 and 2: the runtime


def read_jsonl(name: str) -> list[dict]:
    path = ROOT / "results" / name
    if not path.exists():
        return []
    rows = []
    for line in path.read_text().splitlines():
        if line.startswith("{"):
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return rows


def kib(value: float) -> str:
    return f"{value / 1024:.1f} KiB" if value < 1024 * 1024 else f"{value / 1048576:.2f} MiB"


def size_section() -> list[str]:
    memory = {r["model"]: r for r in read_jsonl("bench-memory.jsonl") if "arenas" in r}
    if not memory:
        return ["_No bench-memory.jsonl; run `make bench`._"]
    names = [n for n in ("blink-tiny", "blink-small") if n in memory]
    out = ["| | " + " | ".join(names) + " |", "|---" + "|---:" * len(names) + "|"]

    def row(label: str, fn) -> None:
        out.append(f"| {label} | " + " | ".join(fn(memory[n]) for n in names) + " |")

    row("parameters", lambda r: f"{r['parameters']:,}")
    row("container on disk", lambda r: kib(r["weights_bytes"]))
    row("bytes per parameter", lambda r: f"{r['bytes_per_parameter']:.3f}")
    for key, label in (("minimum", "arena, minimum limits"),
                       ("embedded", "arena, embedded limits (128 B state, 4 options)"),
                       ("default", "arena, default limits (16 options)")):
        row(label, lambda r, k=key: kib(r["arenas"][k]))

    shared = next((r for r in read_jsonl("bench-memory.jsonl") if "sessions" in r), None)
    if shared:
        out += ["", f"**{shared['sessions']} concurrent sessions over one model:**", "",
                "| | |", "|---|---:|",
                f"| arena per session (4 options) | {kib(shared['arena_bytes_each'])} |",
                f"| arenas in total | {shared['arena_bytes_total_kib'] / 1024:.1f} MiB |",
                f"| measured resident growth | {shared['rss_growth_kib'] / 1024:.1f} MiB |",
                f"| weight bytes counted again | 0 ({kib(shared['weights_bytes_shared'])}, mapped once) |"]
    return out


def latency_section() -> list[str]:
    neon = read_jsonl("bench-latency.jsonl")
    scalar = {(r["model"], r["path"], r["state_bytes"], r["options"]): r
              for r in read_jsonl("bench-latency-scalar.jsonl")}
    if not neon:
        return ["_No bench-latency.jsonl; run `make bench`._"]

    def micro(value: float) -> str:
        return f"{value:.0f} µs" if value < 1000 else f"{value / 1000:.2f} ms"

    out: list[str] = []
    for model in ("blink-tiny", "blink-small"):
        rows = [r for r in neon if r["model"] == model]
        if not rows:
            continue
        shapes = sorted({(r["state_bytes"], r["options"]) for r in rows})
        out += [f"**{model}**", "",
                "| state bytes | options | decide | cached_state | cached_batch8 | new_menu | cached decisions/s |",
                "|---:|---:|---:|---:|---:|---:|---:|"]
        for state, options in shapes:
            by_path = {r["path"]: r for r in rows
                       if r["state_bytes"] == state and r["options"] == options}
            if len(by_path) < 3:
                continue
            # Per decision, eight questions per blink_score_batch call.
            batch = (micro(by_path["cached_batch8"]["p50_us"])
                     if "cached_batch8" in by_path else "—")
            out.append(
                f"| {state} | {options} | {micro(by_path['decide']['p50_us'])} "
                f"| **{micro(by_path['cached_state']['p50_us'])}** "
                f"| {batch} "
                f"| {micro(by_path['new_menu']['p50_us'])} "
                f"| {by_path['cached_state']['decisions_per_second']:,.0f} |"
            )
        out.append("")

    if scalar:
        out += ["**SIMD.** The NEON kernel against the same build with "
                "`-DBLINK_SCALAR_ONLY=1` (`make scalar`):", "",
                "| model | path | state bytes | scalar p50 | NEON p50 | speedup |",
                "|---|---|---:|---:|---:|---:|"]
        # One row per model and path, at the longest state, where the
        # difference matters most and the table stays readable.
        widest: dict[tuple[str, str], dict] = {}
        for r in neon:
            if r["options"] != 4 or r["path"] == "cached_batch8":
                continue
            key = (r["model"], r["path"])
            if key not in widest or r["state_bytes"] > widest[key]["state_bytes"]:
                widest[key] = r
        for r in widest.values():
            key = (r["model"], r["path"], r["state_bytes"], r["options"])
            if key not in scalar:
                continue
            s_p50 = scalar[key]["p50_us"]
            out.append(f"| {r['model']} | `{r['path']}` | {r['state_bytes']} "
                       f"| {micro(s_p50)} | {micro(r['p50_us'])} "
                       f"| {s_p50 / r['p50_us']:.2f}× |")
    return out


# ------------------------------------------------------------------ tables


def headline(tiny: list[dict], small: list[dict]) -> list[str]:
    if not tiny:
        return []
    rows = [
        ("top-1", "top1"), ("balanced accuracy", "balanced_accuracy"),
        ("macro F1", "macro_f1"), ("NLL", "nll"), ("Brier", "brier"),
        ("ECE", "ece"), ("uniform baseline", "uniform_baseline"),
        ("majority baseline", "majority_baseline"),
    ]
    out = [
        f"{len(tiny)} runs, {tiny[0]['metrics']['rows']} test rows over "
        f"{tiny[0]['data']['groups']} scenario groups whose entities appear in "
        "neither the training nor the validation split. Nothing clipped.",
        "",
        "| | blink-tiny | blink-small |", "|---|---:|---:|",
    ]
    for label, key in rows:
        out.append(f"| {label} | {stat(pick(tiny, key))} | {stat(pick(small, key))} |")
    out += ["", "Per family, which is the part that means anything:", "",
            "| family | rows | blink-tiny | blink-small | uniform |",
            "|---|---:|---:|---:|---:|"]
    for family in sorted(tiny[0].get("by_family", {})):
        out.append(
            f"| `{family}` | {tiny[0]['by_family'][family]['rows']} "
            f"| {stat(pick_family(tiny, family))} "
            f"| {stat(pick_family(small, family))} "
            f"| {tiny[0]['by_family'][family]['uniform_baseline']:.3f} |"
        )
    return out


def calibration(tiny: list[dict]) -> list[str]:
    if not tiny:
        return []
    reference = tiny[0]
    out = [
        "Temperature is fitted on validation, whose entity pool is disjoint "
        "from both training and test, and is then measured here.", "",
        f"| | blink-tiny ({len(tiny)} runs) |", "|---|---:|",
        f"| fitted temperature | {stat([r['model']['temperature'] for r in tiny], 3)} |",
        f"| ECE | {stat(pick(tiny, 'ece'))} |",
        f"| MCE | {stat(pick(tiny, 'mce'))} |",
        f"| NLL | {stat(pick(tiny, 'nll'))} |",
        f"| mean confidence | {stat(pick(tiny, 'mean_confidence'))} |",
        "",
        "Reliability, one run (bins holding at least 40 rows):",
        "", "| confidence bin | rows | mean confidence | accuracy | gap |",
        "|---|---:|---:|---:|---:|",
    ]
    for b in reference["metrics"]["calibration_bins"]:
        if b["count"] >= 40:
            out.append(
                f"| {b['lower']:.2f} – {b['upper']:.2f} | {b['count']} "
                f"| {b['mean_confidence']:.3f} | {b['accuracy']:.3f} "
                f"| {b['mean_confidence'] - b['accuracy']:+.3f} |"
            )
    out += ["", "Risk–coverage, averaged over runs:", "",
            "| confidence threshold | coverage | accuracy when answered |",
            "|---:|---:|---:|"]
    for index, row in enumerate(reference["metrics"]["risk_coverage"]):
        coverage, accuracy = [], []
        for r in tiny:
            entry = r["metrics"]["risk_coverage"][index]
            coverage.append(entry["coverage"])
            if entry["accuracy"] is not None:
                accuracy.append(entry["accuracy"])
        out.append(f"| {row['threshold']:.2f} | {stat(coverage, 3)} | {stat(accuracy)} |")
    return out


def controls(tiny: list[dict], small: list[dict], untrained: dict) -> list[str]:
    out = ["| | intact | shuffled state | shuffled question | uniform |",
           "|---|---:|---:|---:|---:|"]
    for name, reports in (("blink-tiny", tiny), ("blink-small", small)):
        if not reports:
            continue
        out.append(
            f"| {name} | {stat(pick(reports, 'top1'))} "
            f"| {stat([r['controls']['shuffled_state']['top1'] for r in reports])} "
            f"| {stat([r['controls']['shuffled_question']['top1'] for r in reports])} "
            f"| {reports[0]['metrics']['uniform_baseline']:.3f} |"
        )
    if untrained:
        out += ["", "| untrained weights | top-1 | uniform |", "|---|---:|---:|"]
        for name, report in untrained.items():
            out.append(f"| {name} | {report['metrics']['top1']:.4f} "
                       f"| {report['metrics']['uniform_baseline']:.3f} |")
    return out


def perturbations(tiny: list[dict]) -> list[str]:
    if not tiny:
        return []
    out = ["| perturbation | argmax flip rate | mean total variation | top-1 before | after |",
           "|---|---:|---:|---:|---:|"]
    for kind, label in (("reversed_options", "reversed options"),
                        ("irrelevant_suffix", "irrelevant suffix")):
        entries = [r["perturbations"][kind] for r in tiny
                   if isinstance(r.get("perturbations", {}).get(kind), dict)]
        if not entries:
            continue
        out.append(
            f"| {label} | {stat([e['argmax_flip_rate'] for e in entries])} "
            f"| {stat([e['mean_total_variation'] for e in entries])} "
            f"| {stat([e['accuracy_before'] for e in entries])} "
            f"| {stat([e['accuracy_after'] for e in entries])} |"
        )
    return out


def external(wanli: list[dict], fixtures: dict[str, list[dict]],
             wanli256: list[dict] | None = None) -> list[str]:
    out: list[str] = []
    if wanli:
        d = wanli[0]["data"]
        out += [
            "**WANLI**, trained on its own train split — a generalisation test, "
            "not a transfer test. Byte limits were taken from the corpus "
            "(`--limits-from-data`), so nothing is clipped.", "",
            "| | |", "|---|---:|",
            f"| rows | {wanli[0]['metrics']['rows']} |",
            f"| clipped | {d['clipped_rows']} |",
            f"| top-1 | {stat(pick(wanli, 'top1'))} |",
            f"| balanced accuracy | {stat(pick(wanli, 'balanced_accuracy'))} |",
            f"| ECE | {stat(pick(wanli, 'ece'))} |",
            f"| uniform baseline | {wanli[0]['metrics']['uniform_baseline']:.3f} |",
            f"| shuffled state | {stat([r['controls']['shuffled_state']['top1'] for r in wanli])} |",
            f"| shuffled question | {stat([r['controls']['shuffled_question']['top1'] for r in wanli])} |",
            "",
        ]
    if wanli256:
        out += [
            "**The same 256 WANLI rows SemIf evaluates.** Rebuilt from the row "
            "identifiers SemIf commits, in SemIf's display order, from the same "
            "pinned revision. No premise in the subset appears in Blink's "
            "training split.", "",
            "| system | parameters | balanced accuracy |", "|---|---:|---:|",
            "| SemIf, Qwen3.5-4B frozen | 4,000,000,000 | **0.637** |",
            f"| blink-tiny, trained | 390,401 "
            f"| {stat([r['metrics']['balanced_accuracy'] for r in wanli256])} |",
            f"| uniform baseline | — | {wanli256[0]['metrics']['uniform_baseline']:.3f} |",
            "",
            f"Blink's controls on this subset: shuffled state "
            f"{stat([r['controls']['shuffled_state']['top1'] for r in wanli256])}, "
            f"shuffled question "
            f"{stat([r['controls']['shuffled_question']['top1'] for r in wanli256])}. "
            "The margin over the controls is about eight points, not the "
            "eleven the headline suggests.", "",
        ]

    if any(fixtures.values()):
        out += [
            "**Transfer to the external fixtures.** A model trained on the "
            "synthetic corpus, asked for something it has never seen.", "",
            "| fixture | rows | clipped | top-1 | uniform |", "|---|---:|---:|---:|---:|",
        ]
        for name, reports in fixtures.items():
            if not reports:
                continue
            out.append(
                f"| `{name}` | {reports[0]['metrics']['rows']} "
                f"| {reports[0]['data']['clipped_rows']} "
                f"| {stat(pick(reports, 'top1'))} "
                f"| {reports[0]['metrics']['uniform_baseline']:.3f} |"
            )
    return out


# -------------------------------------------------------------------- main


def build_section3() -> str:
    tiny = across_seeds("tiny-synthetic", WORKLOADS["tiny-synthetic"][1])
    small = across_seeds("small-synthetic", WORKLOADS["small-synthetic"][1])
    wanli = across_seeds("tiny-wanli", WORKLOADS["tiny-wanli"][1])
    fixtures = {
        name: [r for r in (
            evaluate(f"tiny-synthetic-s{seed}-{name}", path, ["--bootstrap", "500"],
                     model_label=f"tiny-synthetic-s{seed}")
            for seed in SEEDS) if r]
        for name, path in FIXTURES.items()
    }
    wanli256 = [r for r in (
        evaluate(f"tiny-wanli256-s{seed}", "data/wanli256/test.jsonl",
                 ["--bootstrap", "2000"], model_label=f"tiny-wanli-s{seed}")
        for seed in SEEDS) if r]
    untrained = {}
    for preset in ("tiny", "small"):
        report = ROOT / f"results/eval-{preset}-untrained.json"
        if report.exists():
            untrained[f"blink-{preset}, random"] = json.loads(report.read_text())

    parts = ["", "### Synthetic corpus, held-out entities", ""]
    parts += headline(tiny, small)
    parts += ["", "### Calibration", ""] + calibration(tiny)
    parts += ["", "### Controls", ""] + controls(tiny, small, untrained)
    parts += ["", "### Perturbations", ""] + perturbations(tiny)
    parts += ["", "### External corpora", ""] + external(wanli, fixtures, wanli256)
    return "\n".join(parts)


SECTIONS = {
    "section-1": size_section,
    "section-2": latency_section,
    "section-3": lambda: build_section3().splitlines(),
}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    blocks = {name: "\n".join([begin(name), *fn(), end(name)])
              for name, fn in SECTIONS.items()}

    if not args.write:
        print("\n\n".join(blocks[n] for n in sorted(blocks)))
        return

    path = ROOT / "docs/RESULTS.md"
    text = path.read_text()
    for name, block in blocks.items():
        if begin(name) not in text or end(name) not in text:
            raise SystemExit(f"markers for {name} not found in {path}")
        head = text[:text.index(begin(name))]
        tail = text[text.index(end(name)) + len(end(name)):]
        text = head + block + tail
    path.write_text(text)
    print(f"spliced {len(blocks)} sections into {path}")


if __name__ == "__main__":
    main()
